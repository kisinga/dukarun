#!/usr/bin/env node

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const app = process.argv[2];
const allowedApps = new Set(['web', 'storefront', 'super-admin']);

if (!allowedApps.has(app)) {
  console.error(`Usage: node scripts/generate-environment.mjs <${[...allowedApps].join('|')}>`);
  process.exit(2);
}

const localUrl = 'http://127.0.0.1:54321';
const localAnonKey =
  'eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJpc3MiOiJzdXBhYmFzZS1kZW1vIiwicm9sZSI6ImFub24iLCJleHAiOjE5ODM4MTI5OTZ9.CRXP1A7WOeoJeXxjNni43kdQwgnWNReilDMblYTn_I0';
const supabaseUrl = process.env.SUPABASE_URL?.trim() || localUrl;
const supabaseAnonKey = process.env.SUPABASE_ANON_KEY?.trim() || localAnonKey;

try {
  new URL(supabaseUrl);
} catch {
  console.error('SUPABASE_URL must be a valid absolute URL.');
  process.exit(2);
}

if (!process.env.SUPABASE_URL || !process.env.SUPABASE_ANON_KEY) {
  console.warn(
    `[env:${app}] SUPABASE_URL/SUPABASE_ANON_KEY not fully set; compiling against the local Supabase defaults.`
  );
}

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const target = resolve(
  repositoryRoot,
  'apps',
  app,
  'src',
  'environments',
  'environment.generated.ts'
);
const contents =
  `// Generated by scripts/generate-environment.mjs. Do not edit or commit.\n` +
  `export const environment = {\n` +
  `  production: true,\n` +
  `  supabaseUrl: ${JSON.stringify(supabaseUrl)},\n` +
  `  supabaseAnonKey: ${JSON.stringify(supabaseAnonKey)},\n` +
  `};\n`;

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, contents, { encoding: 'utf8', mode: 0o600 });
console.log(`[env:${app}] wrote ${target}`);
